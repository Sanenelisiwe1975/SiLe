/**
 * Generates src/generated.ts from Forge artifacts + contracts/deployments/*.json.
 * Run after `forge build`: pnpm gen:abi
 */
import { readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { getAddress } from 'viem'

const root = join(dirname(fileURLToPath(import.meta.url)), '../../..')
const contracts = join(root, 'contracts')
const CONTRACTS = ['PlanRegistry', 'SubscriptionLedger'] as const

const camel = (s: string) => s[0]!.toLowerCase() + s.slice(1)
let out = '// AUTO-GENERATED by packages/abi/scripts/gen.ts. Do not edit.\n\n'

for (const name of CONTRACTS) {
  const artifact = JSON.parse(readFileSync(join(contracts, 'out', `${name}.sol`, `${name}.json`), 'utf8'))
  out += `export const ${camel(name)}Abi = ${JSON.stringify(artifact.abi, null, 2)} as const\n\n`
}

const deployments: Record<number, Record<string, unknown>> = {}
for (const f of readdirSync(join(contracts, 'deployments')).filter((f) => f.endsWith('.json'))) {
  const d = JSON.parse(readFileSync(join(contracts, 'deployments', f), 'utf8'))
  deployments[d.chainId] = {
    planRegistry: getAddress(d.PlanRegistry),
    subscriptionLedger: getAddress(d.SubscriptionLedger),
    operator: getAddress(d.operator),
    startBlock: d.startBlock,
  }
}
out += `export const deployments = ${JSON.stringify(deployments, null, 2)} as const\n`

writeFileSync(join(root, 'packages/abi/src/generated.ts'), out)
console.log(`wrote ${CONTRACTS.join(', ')} ABIs + deployments for chains ${Object.keys(deployments).join(', ')}`)
